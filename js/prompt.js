// Спрашивает о недочётах — весь журнал; иначе — только частые, чтобы следить за ними
const ASK_FLAWS_RE = /недоч[её]т|ошиб(к|аешь|ся)|минус|косяк|промах|слаб(ое|ые|ост)|что ты (делаешь )?не так|над ч[её]м (тебе )?работать|самоанализ|проанализируй себя/i;
function mistakesBlock(query) {
  const open = openMistakes();
  const fmt = m => `- ${m.what}${m.fix ? " → исправляю: " + m.fix : ""} (${new Date(m.ts).toLocaleDateString("ru-RU")}${(m.count || 1) > 1 ? ", повторов: " + m.count : ""}; ${m.src || ""}${m.status === "fixed" ? "; не повторялось 2 недели — исправлено" : ""})`;
  if (ASK_FLAWS_RE.test(query || "")) {
    const fixed = D.mistakes.filter(m => m.status === "fixed").slice(-10);
    return `ЖУРНАЛ ТВОИХ НЕДОЧЁТОВ (спрашивают о твоих ошибках — отвечай ТОЛЬКО по журналу и реальной переписке: конкретно, с датами, что повторяется, что исправлено. Не выдумывай общих слабостей ИИ. Журнал пуст — так и скажи):
Текущие:
${open.slice(-25).map(fmt).join("\n") || "(нет)"}
Исправленные:
${fixed.map(fmt).join("\n") || "(нет)"}
`;
  }
  const top = open.slice().sort((a, b) => (b.count || 1) - (a.count || 1) || b.last - a.last).slice(0, 5);
  return top.length ? `ТВОИ НЕДАВНИЕ НЕДОЧЁТЫ (следи, чтобы не повторять):\n${top.map(m => "- " + m.what + (m.fix ? " → " + m.fix : "")).join("\n")}\n` : "";
}

/* Проект: его дела, заметки (в т. ч. решения) и материалы — рабочий контекст для «что осталось?», «что мы решили?». */
function projectBlock(now) {
  const others = D.projects.map(p => p.name);
  const cur = D.projects.find(p => p.id === D.meta.currentProject);
  if (!cur) return `ПРОЕКТЫ: ${others.length ? others.join(", ") : "(пока нет)"}. Сейчас общий разговор, вне проекта.`;
  const tasks = D.tasks.filter(t => t.project === cur.id && !t.done);
  const notes = D.notes.filter(n => n.project === cur.id).slice(-30);
  const docs = D.docs.filter(d => d.project === cur.id);
  return `ТЕКУЩИЙ ПРОЕКТ: «${cur.name}». «Что осталось?», «что решили?», «продолжим» — про него. Новые дела и заметки по умолчанию относятся к нему.
Дела проекта:
${tasks.map(t => `- [${t.id}] ${t.text}${t.due ? " — " + isoLocal(t.due) + (t.due < now ? " (ПРОСРОЧЕНО)" : "") : ""}`).join("\n") || "(нет)"}
Заметки и решения проекта:
${notes.map(n => `- [${n.id}] ${isoLocal(n.ts).slice(0, 10)}: ${n.text}`).join("\n") || "(нет)"}
Материалы проекта: ${docs.map(d => "«" + d.title + "»").join(", ") || "(нет)"}
Другие проекты: ${others.filter(n => n !== cur.name).join(", ") || "(нет)"}`;
}

